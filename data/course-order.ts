/**
 * ЕДИНЫЙ ИСТОЧНИК ПОРЯДКА ПРОХОЖДЕНИЯ КУРСА.
 *
 * Значения — это `id` встречи (он же код M{N} и сегмент URL `/meeting/{id}`),
 * а позиция в массиве — номер урока, который видит студент.
 *
 * Маршрут: вступление → визуальный слой (что видит пользователь) → research
 * (почему это работает) → проекты. Тот же принцип, что в разборе Marvel Snap:
 * «смотрим что есть → разбираем зачем». Юзабилити-тест (M4) стоит после
 * проектирования — иначе студент учится тестировать, не имея чего тестировать.
 *
 * Коды M{N} НЕ переприсваиваем: на них ссылается ~80 мест в тексте уроков,
 * а M14 отдельно учит соответствию «M6 = теория цвета» и проверяет квизом.
 *
 * Отсюда же берётся порядок воронки в /admin — чтобы кривая отвала читалась
 * в порядке прохождения, а не по алфавиту.
 *
 * Файл намеренно без импортов: его тянет и админка, и данные курса.
 */
export const COURSE_ORDER = [
  '1', // Введение в UX/UI
  '2', // История и роли
  '6', // Теория цвета
  '7', // Типографика и сетки
  '8', // Визуальная иерархия
  '9', // Wireframing
  '10', // Прототипирование
  '11', // Handoff и итерации
  '12', // Платформы
  '3', // UX Research: основы
  '4', // UX Research: практика
  '5', // User Research методы
  '13', // Финальный проект
  '14', // Разбор Marvel Snap
] as const

/** Позиция урока в маршруте (1-based). 0 — если урок вне маршрута. */
export function coursePosition(meetingId: string): number {
  return (COURSE_ORDER as readonly string[]).indexOf(meetingId) + 1
}
